/**
 * Every tunable option of the site is declared here once and then rendered
 * automatically by the super-admin control panel (/admin/settings).
 *
 * - `public: true`  -> exposed to the frontend through GET /api/settings
 * - `secret: true`  -> never sent to the browser, masked in the admin UI
 */
export type SettingType =
  | 'string'
  | 'text'
  | 'number'
  | 'boolean'
  | 'select'
  | 'color'
  | 'password'
  | 'json'
  | 'image';

export interface SettingField {
  key: string;
  label: string;
  type: SettingType;
  default: string | number | boolean;
  group: string;
  description?: string;
  options?: { value: string; label: string }[];
  min?: number;
  max?: number;
  step?: number;
  public?: boolean;
  secret?: boolean;
  placeholder?: string;
  /** Upload sub-directory used by `type: 'image'` fields. */
  uploadCategory?: string;
}

export interface SettingGroup {
  key: string;
  name: string;
  description: string;
  icon: string;
}

