export function defaultSettings(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const field of SETTINGS) out[field.key] = serializeSetting(field.default, field.type);
  return out;
}

export function serializeSetting(value: unknown, type: SettingType): string {
  if (type === 'boolean') return value ? 'true' : 'false';
  if (type === 'json') {
    return typeof value === 'string' ? value : JSON.stringify(value ?? []);
  }
  return String(value ?? '');
}

export function parseSetting(raw: string | undefined, field: SettingField): unknown {
  if (raw === undefined) return field.default;
  switch (field.type) {
    case 'boolean':
      return raw === 'true' || raw === '1';
    case 'number': {
      const num = Number(raw);
      return Number.isFinite(num) ? num : Number(field.default);
    }
    case 'json': {
      try {
        return JSON.parse(raw);
      } catch {
        return field.default;
      }
    }
    default:
      return raw;
  }
}
