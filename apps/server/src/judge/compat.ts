interface CompatState {
  checked: boolean;
  includeDir: string | null;
}

const state: CompatState = { checked: false, includeDir: null };

function compilerSupports(compiler: string, header: string): boolean {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ogoj-probe-'));
  try {
    const source = path.join(dir, 'probe.cpp');
    fs.writeFileSync(source, `#include <${header}>\nint main() { return 0; }\n`, 'utf8');
    const result = spawnSync(compiler, ['-fsyntax-only', 'probe.cpp'], {
      cwd: dir,
      encoding: 'utf8',
      timeout: 20000,
    });
    return result.status === 0;
  } catch {
    return false;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * Returns the extra include directory needed to compile `#include <bits/stdc++.h>`,
 * or `null` when the compiler already supports it.
 */
export function bitsIncludeDir(compiler: string): string | null {
  if (state.checked) return state.includeDir;
  state.checked = true;
  if (compilerSupports(compiler, 'bits/stdc++.h')) {
    state.includeDir = null;
    return null;
  }
  const dir = path.join(config.paths.judge, 'include', 'bits');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'stdc++.h'), SHIM_HEADER, 'utf8');
  state.includeDir = path.join(config.paths.judge, 'include');
  return state.includeDir;
}

export function resetCompatCache(): void {
  state.checked = false;
  state.includeDir = null;
}
