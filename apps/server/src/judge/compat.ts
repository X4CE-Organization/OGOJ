/**
 * Cross-platform compatibility helpers for the judge.
 *
 * Apple's clang (which is what `g++` usually points to on macOS) ships without
 * `<bits/stdc++.h>`, a header that most competitive programmers use by default.
 * When the configured compiler cannot find it we generate a drop-in shim and
 * add its directory to the include path, so the same source file compiles on
 * Linux and macOS.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { config } from '../config.js';

